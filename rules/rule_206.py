# A tensor's dimension should be equal to either the integer value or the integer value minus one. (Rule 206)

rule_206 = lambda s, v: (
    s.add(Or(v["arg1_ndim"] == v["arg2_value"], v["arg1_ndim"] == v["arg2_value"] - 1))
)

def rule_206_func(arg1, arg2, solver=None):
    arg1 = next(iter(arg1.values()))
    arg2 = next(iter(arg2.values()))

    # Invariant learning phase
    if not solver:
        if not (isinstance(arg1, np.ndarray)):
            return False
        if not ((isinstance(arg2, (int, np.integer)) and not isinstance(arg2, bool))):
            return False

        # Variable declarations
        solver = Solver()
        arg1_ndim = Int('arg1_ndim')
        arg2_value = Int('arg2_value')

        # Value assignments
        solver.add(arg1_ndim == arg1.ndim)
        solver.add(arg2_value == int(arg2))

        # Constraints for rule 206
        rule_206(solver, {'arg1_ndim': arg1_ndim, 'arg2_value': arg2_value})
        return solver.check() == sat

    # Fuzz input generation phase
    else:
        rule_206(solver, {'arg1_ndim': arg1['ndim'], 'arg2_value': arg2['value']})
